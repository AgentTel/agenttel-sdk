#!/usr/bin/env python3
"""Generate the OpenTelemetry Weaver registry for the reliability.* proposal from attributes.json.

Only entries with upstream.status candidate are included: they are the first proposal.
model/reliability/ uses the layout of the semantic-conventions repository, so it can be
copied into that repository's model/ directory as is. model/manifest.yaml lets Weaver
check it on its own.

A candidate is never removed once proposed. To rename one, keep it with stability
deprecated and upstream.renamed_to set to its replacement; it is emitted with a
deprecated block, the form OpenTelemetry uses for renames.

    python3 scripts/generate-semconv-registry.py           # write the files
    python3 scripts/generate-semconv-registry.py --check   # fail if any file is stale
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Code generated by scripts/generate-semconv-registry.py from attributes.json. DO NOT EDIT.\n"

# One attribute group per namespace. Briefs describe only the candidate attributes.
GROUPS = {
    "agenttel.topology": ("Reliability Topology Attributes",
                          "Ownership, criticality and dependencies of a service, declared by its owner."),
    "agenttel.baseline": ("Reliability Baseline Attributes",
                          "The normal behavior of an operation, declared by its owner."),
    "agenttel.decision": ("Reliability Decision Attributes",
                          "How an operation may be handled when it fails, declared by its owner."),
    "agenttel.slo": ("Reliability SLO Attributes",
                     "The service level objective an operation counts towards."),
    "agenttel.dependency": ("Reliability Dependency Attributes",
                            "A dependency of the service whose health changed."),
}
TYPES = {"string": "string", "int": "int", "double": "double", "boolean": "boolean", "string[]": "string[]"}
PLAIN = re.compile(r"^[A-Za-z][A-Za-z0-9 ,.'()_/-]*$")


def scalar(value):
    """A YAML scalar: plain when unambiguous, otherwise JSON-quoted (valid YAML)."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    if PLAIN.match(value) and value.lower() not in ("true", "false", "null", "yes", "no"):
        return value
    return json.dumps(value)


def sentence(text):
    return text if text.endswith(".") else text + "."


def load():
    schema = json.loads((ROOT / "attributes.json").read_text())
    groups = {}
    for ns_name, ns in schema["namespaces"].items():
        attrs = [a for a in ns["attributes"].values() if a["upstream"]["status"] == "candidate"]
        if attrs:
            if ns_name not in GROUPS:
                sys.exit(f"{ns_name} has candidate attributes but no entry in GROUPS")
            groups[ns_name] = attrs
    events = []
    for name, e in schema["events"].items():
        if e["upstream"]["status"] != "candidate":
            continue
        prefix = e["attributes"].rstrip("*")
        refs = [a["upstream"]["key"] for attrs in groups.values() for a in attrs if a["key"].startswith(prefix)]
        if not refs:
            sys.exit(f"{name}: no candidate attributes match {e['attributes']}")
        events.append((e, refs))
    return groups, events


def attribute(a):
    renamed_to = a["upstream"].get("renamed_to")
    # OTel keeps a deprecated attribute's stability and marks it with a deprecated block
    stability = "development" if a["stability"] == "deprecated" else a["stability"]
    out = [f"      - id: {a['upstream']['key']}"]
    if "enum" in a:
        out.append("        type:")
        out.append("          members:")
        for value in a["enum"]:
            out += [
                f"            - id: {value}",
                f"              value: {scalar(value)}",
                f"              brief: {scalar(a['enum_briefs'][value])}",
                f"              stability: {stability}",
            ]
    else:
        out.append(f"        type: {TYPES[a['type']]}")
    out.append(f"        stability: {stability}")
    if renamed_to:
        out += ["        deprecated:", "          reason: renamed", f"          renamed_to: {renamed_to}"]
    out.append(f"        brief: {scalar(sentence(a['description']))}")
    if "note" in a:
        out.append(f"        note: {scalar(a['note'])}")
    if "examples" in a:
        out.append("        examples: [" + ", ".join(scalar(x) for x in a["examples"]) + "]")
    return out


def registry(groups):
    out = [HEADER + "groups:"]
    for ns_name, attrs in groups.items():
        display, brief = GROUPS[ns_name]
        out += [
            f"  - id: registry.{attrs[0]['upstream']['key'].rsplit('.', 1)[0]}",
            "    type: attribute_group",
            f"    display_name: {display}",
            f"    brief: {scalar(brief)}",
            "    attributes:",
        ]
        for a in attrs:
            out += attribute(a)
    return "\n".join(out) + "\n"


def events_file(events):
    out = [HEADER + "groups:"]
    for e, refs in events:
        name = e["upstream"]["key"]
        out += [
            f"  - id: event.{name}",
            "    type: event",
            f"    name: {name}",
            f"    stability: {e['stability']}",
            f"    brief: {scalar(sentence(e['description']))}",
            "    attributes:",
        ]
        for ref in refs:
            out += [f"      - ref: {ref}", "        requirement_level: required"]
    return "\n".join(out) + "\n"


def manifest():
    return HEADER + """file_format: definition_manifest/2.0
name: reliability
description: Reliability telemetry conventions proposed by AgentTel.
schema_url: https://agenttel.dev/schemas/reliability/0.1.0
"""


def main():
    check = "--check" in sys.argv[1:]
    groups, events = load()
    files = {
        "model/manifest.yaml": manifest(),
        "model/reliability/registry.yaml": registry(groups),
        "model/reliability/events.yaml": events_file(events),
    }
    stale = []
    for rel, content in files.items():
        path = ROOT / rel
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Stale Weaver registry (run python3 scripts/generate-semconv-registry.py):")
        for rel in stale:
            print(f"    {rel}")
        sys.exit(1)
    if not check:
        count = sum(len(a) for a in groups.values())
        print(f"Wrote {len(files)} files: {count} attributes, {len(events)} events")


if __name__ == "__main__":
    main()
