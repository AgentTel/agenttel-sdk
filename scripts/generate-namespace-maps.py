#!/usr/bin/env python3
"""Generate each SDK's legacy-to-standard attribute key map from attributes.json.

An attribute or event is mapped when its upstream.status is candidate, later or
otel_existing and its upstream.key differs from its key. The SDKs use these maps
for the agenttel.attributes.namespace setting (legacy | standard | both).

    python3 scripts/generate-namespace-maps.py           # write the files
    python3 scripts/generate-namespace-maps.py --check   # fail if any file is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAPPED = ("candidate", "later", "otel_existing")
HEADER = "Code generated by scripts/generate-namespace-maps.py from attributes.json. DO NOT EDIT."


def load_maps():
    schema = json.loads((ROOT / "attributes.json").read_text())
    attrs = {}
    for ns in schema["namespaces"].values():
        for a in ns["attributes"].values():
            u = a["upstream"]
            if u["status"] in MAPPED and u["key"] != a["key"]:
                attrs[a["key"]] = u["key"]
    events = {}
    for name, e in schema["events"].items():
        u = e["upstream"]
        if u["status"] in MAPPED and u["key"] != name:
            events[name] = u["key"]
    return dict(sorted(attrs.items())), dict(sorted(events.items()))


def java(attrs, events):
    def entries(m):
        return ",\n".join(f'            Map.entry("{k}", "{v}")' for k, v in m.items())
    return f"""// {HEADER}
package io.agenttel.api.attributes;

import java.util.Map;

/**
 * Standard OpenTelemetry names for AgentTel attribute keys and event names, used by the
 * {{@code agenttel.attributes.namespace}} setting. Keys without an entry keep their name.
 */
public final class AttributeNamespaces {{

    private AttributeNamespaces() {{}}

    /** Legacy {{@code agenttel.*}} attribute key to its standard key. */
    public static final Map<String, String> ATTRIBUTES = Map.ofEntries(
{entries(attrs)});

    /** Legacy {{@code agenttel.*}} event name to its standard event name. */
    public static final Map<String, String> EVENTS = Map.ofEntries(
{entries(events)});
}}
"""


def go(attrs, events):
    def entries(m):
        width = max(len(k) for k in m) + 3
        return "\n".join(f'\t{(chr(34) + k + chr(34) + ":").ljust(width)} "{v}",' for k, v in m.items())
    return f"""// {HEADER}

package attributes

// StandardAttributeKeys maps legacy agenttel.* attribute keys to their standard
// OpenTelemetry keys, for the agenttel.attributes.namespace setting. Keys without
// an entry keep their name.
var StandardAttributeKeys = map[string]string{{
{entries(attrs)}
}}

// StandardEventNames maps legacy agenttel.* event names to their standard names.
var StandardEventNames = map[string]string{{
{entries(events)}
}}
"""


def ts(attrs, events):
    def entries(m):
        return "\n".join(f"  '{k}': '{v}'," for k, v in m.items())
    return f"""// {HEADER}

/**
 * Legacy `agenttel.*` attribute keys mapped to their standard OpenTelemetry keys,
 * for the `agenttel.attributes.namespace` setting. Keys without an entry keep their name.
 */
export const STANDARD_ATTRIBUTE_KEYS: Readonly<Record<string, string>> = {{
{entries(attrs)}
}};

/** Legacy `agenttel.*` event names mapped to their standard names. */
export const STANDARD_EVENT_NAMES: Readonly<Record<string, string>> = {{
{entries(events)}
}};
"""


def py(attrs, events):
    def entries(m):
        return "\n".join(f'    "{k}": "{v}",' for k, v in m.items())
    return f'''# {HEADER}
"""Legacy ``agenttel.*`` attribute keys and event names mapped to their standard
OpenTelemetry names, for the ``agenttel.attributes.namespace`` setting. Keys without
an entry keep their name."""

from __future__ import annotations

from types import MappingProxyType

STANDARD_ATTRIBUTE_KEYS = MappingProxyType({{
{entries(attrs)}
}})

STANDARD_EVENT_NAMES = MappingProxyType({{
{entries(events)}
}})
'''


TARGETS = {
    "agenttel-api/src/main/java/io/agenttel/api/attributes/AttributeNamespaces.java": java,
    "agenttel-go/attributes/namespaces.go": go,
    "agenttel-node/src/namespaces.ts": ts,
    "agenttel-python/src/agenttel/namespaces.py": py,
}


def main():
    check = "--check" in sys.argv[1:]
    attrs, events = load_maps()
    stale = []
    for rel, render in TARGETS.items():
        path = ROOT / rel
        content = render(attrs, events)
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.write_text(content)
    if stale:
        print("Stale generated namespace maps (run python3 scripts/generate-namespace-maps.py):")
        for rel in stale:
            print(f"    {rel}")
        sys.exit(1)
    if not check:
        print(f"Wrote {len(TARGETS)} files: {len(attrs)} attribute keys, {len(events)} event names")


if __name__ == "__main__":
    main()
